def remove_expma_case(text: str) -> str:
    pattern = r"\n### 0\.7 案例：2018年2月贵州燃气\n.*?(?=\n### 0\.8 信号有效性原则)"
    text = re.sub(pattern, "\n", text, flags=re.S)
    text = text.replace("### 0.8 信号有效性原则", "### 0.7 信号有效性原则")
    return text


